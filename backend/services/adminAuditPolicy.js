const definitions = Object.freeze({
  'product.created': 'product',
  'product.updated': 'product',
  'product.archived': 'product',
  'product.flash_sale_activated': 'product',
  'product.flash_sale_deactivated': 'product',
  'order.payment_confirmed': 'order',
  'order.status_updated': 'order',
  'order.contact_confirmed': 'order',
  'order.cancelled': 'order',
  'user.role_changed': 'user',
  'user.deleted': 'user',
  'appearance.updated': 'appearance',
  'coupon.created': 'coupon',
  'coupon.status_updated': 'coupon',
  'review.moderated': 'review',
  'message.deleted': 'message',
  'subscriber.deleted': 'subscriber',
});
const validators = {
  price: (v) => typeof v === 'number' && Number.isFinite(v) && v >= 0,
  stock: (v) => Number.isInteger(v) && v >= 0,
  originalPrice: (v) => v === null || (typeof v === 'number' && Number.isFinite(v) && v >= 0),
  flashSale: (v) => typeof v === 'boolean',
  flashSaleDiscount: (v) => typeof v === 'number' && v >= 0 && v <= 100,
  flashSaleEndsAt: (v) => v === null || v instanceof Date,
  archivedAt: (v) => v instanceof Date,
  status: (v) =>
    [
      'pending',
      'processing',
      'shipped',
      'delivered',
      'completed',
      'cancelled',
      'approved',
      'rejected',
      'hidden',
    ].includes(v),
  paymentStatus: (v) => ['pending', 'paid', 'failed'].includes(v),
  role: (v) => ['user', 'admin'].includes(v),
  theme: (v) => ['normal', 'halloween', 'christmas'].includes(v),
  active: (v) => typeof v === 'boolean',
  discountPercent: (v) => typeof v === 'number' && v >= 1 && v <= 100,
  maxDiscountAmount: (v) => typeof v === 'number' && Number.isFinite(v) && v >= 0,
  minOrderAmount: (v) => typeof v === 'number' && Number.isFinite(v) && v >= 0,
  maxRedemptions: (v) => Number.isInteger(v) && v > 0,
  expiresAt: (v) => v instanceof Date,
};
const fields = {
  product: [
    'price',
    'stock',
    'originalPrice',
    'flashSale',
    'flashSaleDiscount',
    'flashSaleEndsAt',
    'archivedAt',
  ],
  order: ['status', 'paymentStatus'],
  user: ['role'],
  appearance: ['theme'],
  coupon: [
    'active',
    'discountPercent',
    'maxDiscountAmount',
    'minOrderAmount',
    'maxRedemptions',
    'expiresAt',
  ],
  review: ['status'],
};
module.exports = { definitions, validators, fields };
